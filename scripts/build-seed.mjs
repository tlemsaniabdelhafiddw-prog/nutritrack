#!/usr/bin/env node
// Builds supabase/migrations/*_seed_starter_data.sql from the starter food and
// recipe files. Recipe nutrition is computed here from ingredient grams and the
// food dataset so the two always agree.
//
// Usage: node scripts/build-seed.mjs

import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';
import { foods, STARTER_NOTE } from '../supabase/seed/starter-foods.mjs';
import { recipes } from '../supabase/seed/starter-recipes.mjs';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const out = join(root, 'supabase/migrations/20261027000003_seed_starter_data.sql');

const q = (v) => (v === null || v === undefined ? 'null' : `'${String(v).replace(/'/g, "''")}'`);
const arr = (a) => `array[${a.map(q).join(', ')}]::text[]`;
const num = (n) => (n === null || n === undefined ? 'null' : String(n));
const foodId = (key) => `md5('nutritrack-food:${key}')::uuid`;
const recipeId = (slug) => `md5('nutritrack-recipe:${slug}')::uuid`;
const round1 = (n) => Math.round(n * 10) / 10;

const byKey = new Map();
for (const f of foods) {
  const [key, , , , , kcal, p, c, fat, fiber] = f;
  if (byKey.has(key)) throw new Error(`duplicate food key ${key}`);
  // Sanity check: Atwater energy from macros should be in the same ballpark as stated kcal.
  const atwater = p * 4 + c * 4 + fat * 9;
  if (kcal > 20 && Math.abs(atwater - kcal) / kcal > 0.25) {
    console.warn(`check ${key}: stated ${kcal} kcal vs ${atwater.toFixed(0)} from macros`);
  }
  byKey.set(key, { kcal, p, c, fat, fiber: fiber ?? 0, row: f });
}

const lines = [];
lines.push('-- Generated by scripts/build-seed.mjs. Do not edit by hand.');
lines.push('-- Starter foods are approximate reference values; see supabase/seed/starter-foods.mjs.');
lines.push('');
lines.push('insert into public.foods (id, name, name_fr, name_ar, aliases, category, kcal_100g, protein_100g, carbs_100g, fat_100g, fiber_100g, serving_unit, serving_grams, source, source_id) values');
lines.push(
  foods
    .map(([key, en, fr, ar, cat, kcal, p, c, f, fib, unit, grams, aliases]) =>
      `  (${foodId(key)}, ${q(en)}, ${q(fr)}, ${q(ar)}, ${arr(aliases)}, ${q(cat)}, ${num(kcal)}, ${num(p)}, ${num(c)}, ${num(f)}, ${num(fib)}, ${q(unit)}, ${num(grams)}, 'starter', ${q(key)})`,
    )
    .join(',\n') + '\non conflict (id) do nothing;',
);
lines.push(`update public.foods set source_note = ${q(STARTER_NOTE)} where source = 'starter' and source_note is null;`);
lines.push('');

const summary = [];
for (const r of recipes) {
  let kcal = 0, p = 0, c = 0, fat = 0, fiber = 0;
  for (const [key, grams] of r.ingredients) {
    const f = byKey.get(key);
    if (!f) throw new Error(`recipe ${r.slug}: unknown food ${key}`);
    kcal += (f.kcal * grams) / 100;
    p += (f.p * grams) / 100;
    c += (f.c * grams) / 100;
    fat += (f.fat * grams) / 100;
    fiber += (f.fiber * grams) / 100;
  }
  const s = r.servings;
  const per = {
    kcal: round1(kcal / s), p: round1(p / s), c: round1(c / s), fat: round1(fat / s), fiber: round1(fiber / s),
  };
  summary.push(`${r.slug}: ${per.kcal} kcal, P ${per.p} C ${per.c} F ${per.fat} fiber ${per.fiber}`);

  lines.push(`-- ${r.slug}`);
  lines.push(
    `insert into public.recipes (id, slug, title, title_fr, title_ar, description, description_fr, description_ar, image_url, image_credit, servings, prep_minutes, cook_minutes, meal_types, diet_tags, allergens, kcal_per_serving, protein_per_serving, carbs_per_serving, fat_per_serving, fiber_per_serving, is_public) values (` +
      [
        recipeId(r.slug), q(r.slug), q(r.title[0]), q(r.title[1]), q(r.title[2]),
        q(r.description[0]), q(r.description[1]), q(r.description[2]),
        q(r.imageUrl ?? null), q(r.imageCredit ?? null),
        num(s), num(r.prep), num(r.cook), arr(r.mealTypes), arr(r.dietTags), arr(r.allergens),
        num(per.kcal), num(per.p), num(per.c), num(per.fat), num(per.fiber), 'true',
      ].join(', ') +
      ') on conflict (slug) do nothing;',
  );
  lines.push('insert into public.recipe_ingredients (recipe_id, position, food_id, name, name_fr, name_ar, quantity, unit, grams) values');
  lines.push(
    r.ingredients
      .map(([key, grams, qty, unit, override], i) => {
        const [, en, fr, ar] = byKey.get(key).row;
        const names = override ?? [en, fr, ar];
        return `  (${recipeId(r.slug)}, ${i + 1}, ${foodId(key)}, ${q(names[0])}, ${q(names[1])}, ${q(names[2])}, ${num(qty)}, ${q(unit)}, ${num(grams)})`;
      })
      .join(',\n') + '\non conflict (recipe_id, position) do nothing;',
  );
  lines.push('insert into public.recipe_instructions (recipe_id, step, body, body_fr, body_ar) values');
  lines.push(
    r.steps
      .map(([en, fr, ar], i) => `  (${recipeId(r.slug)}, ${i + 1}, ${q(en)}, ${q(fr)}, ${q(ar)})`)
      .join(',\n') + '\non conflict (recipe_id, step) do nothing;',
  );
  lines.push('');
}

writeFileSync(out, lines.join('\n'));
console.log(`wrote ${out}`);
console.log(`${foods.length} foods, ${recipes.length} recipes`);
console.log(summary.join('\n'));
